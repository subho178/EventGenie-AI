/**
 * Export and Sharing Routes
 * Generates formatted Markdown, raw JSON backup, and shareable summaries.
 */

import express from 'express';
import { getEventById } from '../services/storage.js';
import { formatCurrency } from '../services/budgetCalculator.js';

const router = express.Router();

/**
 * GET /api/export/:id/markdown
 * Returns downloadable/readable Markdown document of the full plan.
 */
router.get('/:id/markdown', (req, res) => {
  const event = getEventById(req.params.id);
  if (!event) {
    return res.status(404).send('Event plan not found');
  }

  const curr = event.currency || 'USD';
  const totalBudgetFormatted = formatCurrency(event.totalBudget, curr);
  const allocatedFormatted = formatCurrency(event.budget?.totalAllocated || 0, curr);
  const remainingFormatted = formatCurrency(event.budget?.remainingBalance || 0, curr);

  let md = `# Event Plan: ${event.eventName}\n\n`;
  md += `**Event Type:** ${event.eventType.toUpperCase()}  \n`;
  md += `**Date:** ${event.eventDate} ${event.startTime ? `(${event.startTime} - ${event.endTime || 'End'})` : ''}  \n`;
  md += `**Location:** ${event.location}  \n`;
  md += `**Guest Count:** ${event.guestCount} attendees  \n`;
  md += `**Total Budget:** ${totalBudgetFormatted}  \n`;
  md += `**Generation Engine:** ${event.aiModelUsed || 'EventGenie AI'} (${event.generationMode === 'gemini' ? 'Live AI' : 'Algorithmic Mode'})\n\n`;

  md += `## 🌟 Vision & Concept\n${event.summary?.concept || 'Tailored event concept.'}\n\n`;
  if (event.summary?.assumptions) {
    md += `*Planning Assumptions:* ${event.summary.assumptions}\n\n`;
  }

  md += `## 💰 Smart Budget Summary\n`;
  md += `- **Total Budget:** ${totalBudgetFormatted}\n`;
  md += `- **Total Estimated Spend:** ${allocatedFormatted}\n`;
  md += `- **Remaining Contingency Balance:** ${remainingFormatted}\n`;
  md += `- **Status:** ${event.budget?.isOverBudget ? '⚠️ Over Budget' : '✅ Within Budget'}\n\n`;

  md += `### Expense Categories\n`;
  md += `| Category | Estimated Allocation | % of Budget | Priority | Notes |\n`;
  md += `| :--- | :--- | :--- | :--- | :--- |\n`;
  (event.budget?.categories || []).forEach(cat => {
    md += `| ${cat.name} | ${formatCurrency(cat.allocatedAmount, curr)} | ${cat.percentOfBudget}% | ${cat.priority || 'Medium'} | ${cat.notes || '-'} |\n`;
  });
  md += `\n*Note: All category costs shown are estimates, not binding vendor quotes.*\n\n`;

  md += `## ⏱️ Preparation Timeline\n`;
  md += `| Phase | Milestone Task | Suggested Deadline | Priority | Status | Assigned To |\n`;
  md += `| :--- | :--- | :--- | :--- | :--- | :--- |\n`;
  (event.timeline?.tasks || []).forEach(t => {
    md += `| ${t.phase || 'General'} | ${t.title} | ${t.suggestedDeadline || 'TBD'} | ${t.priority} | ${t.status.toUpperCase()} | ${t.assignedTo || 'Unassigned'} |\n`;
  });
  md += `\n`;

  md += `## 📋 Vendor & Service Requirements\n`;
  md += `| Category | Service Requirement | Status | Est. Cost | Selection Criteria |\n`;
  md += `| :--- | :--- | :--- | :--- | :--- |\n`;
  (event.vendors?.vendors || []).forEach(v => {
    md += `| ${v.category} | ${v.serviceName} | ${v.status.toUpperCase()} | ${formatCurrency(v.estimatedCost, curr)} | ${v.selectionCriteria || '-'} |\n`;
  });
  md += `\n`;

  md += `## 💡 Creative Concepts & Ideas\n`;
  const ideas = event.creativeIdeas || {};
  if (ideas.themeConcepts?.length) {
    md += `### Theme & Decor Concepts\n`;
    ideas.themeConcepts.forEach(i => {
      md += `- **${i.title}:** ${i.description || ''}\n`;
    });
    md += `\n`;
  }
  if (ideas.activitiesAndEntertainment?.length) {
    md += `### Activities & Entertainment\n`;
    ideas.activitiesAndEntertainment.forEach(i => {
      md += `- **${i.title}:** ${i.description || ''}\n`;
    });
    md += `\n`;
  }
  if (ideas.invitationWording?.length) {
    md += `### Sample Invitation Copy\n`;
    ideas.invitationWording.forEach(i => {
      md += `> ${i.description || i.title}\n\n`;
    });
  }

  md += `---\n*Generated by EventGenie AI — Complete Personalized Event Planning Assistant*`;

  res.setHeader('Content-Type', 'text/markdown; charset=utf-8');
  res.setHeader('Content-Disposition', `attachment; filename="${event.eventName.replace(/[^a-zA-Z0-9_-]/g, '_')}_Plan.md"`);
  res.send(md);
});

/**
 * GET /api/export/:id/json
 * Returns raw JSON backup file.
 */
router.get('/:id/json', (req, res) => {
  const event = getEventById(req.params.id);
  if (!event) {
    return res.status(404).json({ success: false, error: 'Event not found' });
  }

  res.setHeader('Content-Type', 'application/json');
  res.setHeader('Content-Disposition', `attachment; filename="${event.eventName.replace(/[^a-zA-Z0-9_-]/g, '_')}_EventGenie.json"`);
  res.json(event);
});

export default router;
